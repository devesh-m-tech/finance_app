const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '../../');
const backendContractDir = path.join(rootDir, 'backend', 'contract');
const frontendGeneratedDir = path.join(rootDir, 'frontend', 'shared', 'generated');

if (!fs.existsSync(frontendGeneratedDir)) {
  fs.mkdirSync(frontendGeneratedDir, { recursive: true });
}

console.log('🔄 Syncing API contract from backend to frontend...');

const openApiSrc = path.join(backendContractDir, 'openapi.json');
const permsSrc = path.join(backendContractDir, 'permissions.json');

const openApiDest = path.join(frontendGeneratedDir, 'openapi.json');
const permsDest = path.join(frontendGeneratedDir, 'permissions.json');

if (fs.existsSync(openApiSrc)) {
  fs.copyFileSync(openApiSrc, openApiDest);
  console.log('✅ Copied openapi.json to frontend/shared/generated/');
} else {
  console.warn('⚠️  backend/contract/openapi.json not found yet.');
}

if (fs.existsSync(permsSrc)) {
  fs.copyFileSync(permsSrc, permsDest);
  console.log('✅ Copied permissions.json to frontend/shared/generated/');

  // Generate typed permission definitions
  try {
    const permsData = JSON.parse(fs.readFileSync(permsSrc, 'utf8'));
    const permissionKeys = permsData.catalog.map(p => `'${p.key}'`).join(' |\n  ');

    const tsContent = `// AUTO-GENERATED BY sync-contract.js - DO NOT EDIT DIRECTLY
export type SystemRole = 'SUPER_ADMIN' | 'MANAGER' | 'SALESPERSON';

export type PermissionKey =
  | ${permissionKeys};

export interface PermissionDefinition {
  key: PermissionKey;
  module: string;
  action: string;
  description: string;
}

export interface RolePermissionsMatrix {
  SUPER_ADMIN: PermissionKey[];
  MANAGER: PermissionKey[];
  SALESPERSON: PermissionKey[];
}
`;
    fs.writeFileSync(path.join(frontendGeneratedDir, 'permission-types.ts'), tsContent, 'utf8');
    console.log('✅ Generated frontend/shared/generated/permission-types.ts');
  } catch (err) {
    console.error('❌ Failed to generate permission types:', err.message);
  }
} else {
  console.warn('⚠️  backend/contract/permissions.json not found yet.');
}

console.log('✨ API Contract sync completed.');
